package com.infinitecanvas.board.domain.port

/**
 * Источник идентификаторов для штрихов и изображений доски.
 *
 * Заменяет `System.nanoTime()`, который не гарантировал ни уникальности
 * (часы/восстановление из бэкапа), ни связи с порядком создания: на этой связи
 * держится порядок наложения штрихов (сортировка по id в draw-фазе).
 *
 * Реализация — `:core:data` (инфраструктура), связывание — `AppContainer`.
 */
interface IdGenerator {

    /**
     * Возвращает следующий идентификатор. Строго больше любого ранее выданного
     * и любого переданного в [seedAtLeast].
     *
     * Вызывается только с main-потока (жесты/контроллеры), но реализация обязана
     * быть безопасной и при конкурентном доступе: это дешёвая атомарная операция.
     */
    fun next(): Long

    /**
     * Поднимает счётчик так, чтобы следующие значения были больше [highestUsed].
     *
     * Нужен при загрузке доски: в файле уже лежат id, и новые обязаны идти после них.
     * Идемпотентен и никогда не понижает счётчик — повторный вызов с меньшим
     * аргументом ничего не меняет. Это даёт уникальность в пределах доски и,
     * как следствие, при повторных открытиях одной и той же доски.
     */
    fun seedAtLeast(highestUsed: Long)
}
